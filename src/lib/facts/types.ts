export interface StoredFact {
  id: string;
  userId: string;
  movie: string;
  content: string;
  createdAt: Date;
}

/** Persistence the fact service needs. Every method is scoped by userId. */
export interface FactRepository {
  getFavoriteMovie(userId: string): Promise<string | null>;
  findLatestFact(userId: string, movie: string): Promise<StoredFact | null>;
  createFact(input: { userId: string; movie: string; content: string; createdAt: Date }): Promise<StoredFact>;
  /** Atomically take the per-user generation lease if it is free or expired. */
  tryAcquireLock(userId: string, token: string, now: Date, expiresAt: Date): Promise<boolean>;
  /** Release the lease, but only if we still hold it (token matches). */
  releaseLock(userId: string, token: string): Promise<void>;
  isLocked(userId: string, now: Date): Promise<boolean>;
}

export interface FactGenerator {
  generate(movie: string): Promise<string>;
}

/** What the API exposes. Deliberately omits userId. */
export interface FactDTO {
  id: string;
  movie: string;
  content: string;
  createdAt: string;
}

export type FactSource =
  | "cache" // a fact for this movie newer than the cache window
  | "generated" // freshly generated by this request
  | "stale-fallback"; // generation failed or was busy; older fact returned instead

export type FactResult =
  | { ok: true; fact: FactDTO; source: FactSource }
  | { ok: false; code: "NO_MOVIE" | "GENERATION_FAILED" | "BUSY"; message: string };
